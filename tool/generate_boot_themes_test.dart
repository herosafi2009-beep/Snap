// Generates the Android splash themes used for the dynamic start-up color.
// Runs inside the Flutter test environment so colors come from exactly the
// same ColorScheme code as the app:
//
//   flutter test tool/generate_boot_themes_test.dart
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:snap/core/theme/app_theme.dart';
import 'package:snap/core/theme/boot_colors.dart';

String _hex(Color c) => '#${c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()}';

void main() {
  test('generate boot splash themes', () {
    const res = 'android/app/src/main/res';
    final day = StringBuffer();
    final night = StringBuffer();
    final themes = StringBuffer();
    final kotlin = StringBuffer();

    Color boot(Color seed, Brightness b) => BootColors.backgroundFor(AppTheme.scheme(seed, b));

    final defaultSeed = AppTheme.defaultSeed;
    day.writeln('    <color name="boot_default">${_hex(boot(defaultSeed, Brightness.light))}</color>');
    night.writeln('    <color name="boot_default">${_hex(boot(defaultSeed, Brightness.dark))}</color>');

    for (var i = 0; i < BootColors.hueBuckets; i++) {
      final seed = BootColors.presetSeed(i);
      final light = _hex(boot(seed, Brightness.light));
      final dark = _hex(boot(seed, Brightness.dark));
      day
        ..writeln('    <color name="boot_$i">$light</color>')
        ..writeln('    <color name="boot_${i}_light">$light</color>')
        ..writeln('    <color name="boot_${i}_dark">$dark</color>');
      night.writeln('    <color name="boot_$i">$dark</color>');
      for (final (suffix, color) in [('', 'boot_$i'), ('Light', 'boot_${i}_light'), ('Dark', 'boot_${i}_dark')]) {
        themes
          ..writeln('    <style name="SnapBoot$suffix$i" parent="LaunchTheme">')
          ..writeln('        <item name="android:windowSplashScreenBackground">@color/$color</item>')
          ..writeln('        <item name="android:windowSplashScreenAnimatedIcon">@mipmap/ic_launcher</item>')
          ..writeln('    </style>');
      }
      kotlin.writeln('        R.style.SnapBoot$i, R.style.SnapBootLight$i, R.style.SnapBootDark$i,');
    }

    const header = '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/generate_boot_themes_test.dart. Do not edit. -->\n<resources>\n';
    File('$res/values/boot_colors.xml').writeAsStringSync('$header$day</resources>\n');
    Directory('$res/values-night').createSync(recursive: true);
    File('$res/values-night/boot_colors.xml').writeAsStringSync('$header$night</resources>\n');
    File('$res/values-v31/boot_themes.xml').writeAsStringSync('$header$themes</resources>\n');
    File('android/app/src/main/kotlin/dev/snap/player/BootThemes.kt').writeAsStringSync('''
// Generated by tool/generate_boot_themes_test.dart. Do not edit.
package dev.snap.player

/** Splash themes indexed by hue bucket * 3 + mode (0 system, 1 light, 2 dark). */
object BootThemes {
    val styles = intArrayOf(
$kotlin    )
}
''');
  });
}
